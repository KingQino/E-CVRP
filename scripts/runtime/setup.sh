#!/usr/bin/env bash
# Prepares the runtime-profile experiment (run on the login node after build-source.sh).
#
#   $ECVRP_ROOT/runtime-profile/
#     Run                       copy of the solver binary
#     instances.txt, arms.tsv   copies of scripts/runtime/{instances.txt,arms.tsv}
#     job.slurm                 Slurm array: one task = one instance; seeds 1-10, both arms alternately, one core
#     <arm>/data -> source/data
#     <arm>/stats/MA/<instance>/<seed>/{profile.tsv,run-summary.tsv,...}
#     timing/<instance>.tsv     process wall time of every run, host and CPU model
#     log/                      Slurm output
#     source-commit.txt
#
# Usage: setup.sh            then: sbatch "$ECVRP_ROOT/runtime-profile/job.slurm"
set -euo pipefail
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../hpc" && pwd)/common.sh"

runtime_dir="$source_dir/scripts/runtime"
project_dir="$root_dir/runtime-profile"
run_binary="$source_dir/build/Run"
[[ -x "$run_binary" ]] || { echo "Error: missing $run_binary; run scripts/hpc/build-source.sh first" >&2; exit 1; }

mkdir -p "$project_dir/log" "$project_dir/timing"
cp "$run_binary" "$project_dir/Run"
cp "$runtime_dir/instances.txt" "$runtime_dir/arms.tsv" "$project_dir/"
while IFS=$'\t' read -r id _; do
    [[ "$id" == "id" || -z "$id" ]] && continue
    mkdir -p "$project_dir/$id"
    [[ -e "$project_dir/$id/data" ]] || ln -s "$source_dir/data" "$project_dir/$id/data"
done < "$runtime_dir/arms.tsv"
{
    git -C "$source_dir" rev-parse --abbrev-ref HEAD
    git -C "$source_dir" rev-parse HEAD
    git -C "$source_dir" status --short
} > "$project_dir/source-commit.txt" 2>/dev/null || true

count="$(grep -cvE '^[[:space:]]*(#|$)' "$project_dir/instances.txt")"
array_max=$((count - 1))

cat > "$project_dir/job.slurm" <<EOL
#!/bin/bash
#SBATCH --job-name=BA-BMA-runtime
#SBATCH --partition=compute
#SBATCH --constraint=ddy
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=1
#SBATCH --mem=4G
#SBATCH --time=12:00:00
#SBATCH --array=0-$array_max
#SBATCH --output=$project_dir/log/%x-%A_%a.out
#SBATCH --chdir=$project_dir

# Generated by scripts/runtime/setup.sh. One array task = one instance: seeds 1-10, and for every seed
# both arms one after the other on the same core, so the two arms see the same node and load.
set -euo pipefail

if type module >/dev/null 2>&1; then
    module purge
    module load $run_modules
fi
export OMP_NUM_THREADS=1

mapfile -t cases < <(grep -vE '^[[:space:]]*(#|\$)' instances.txt)
CASE="\${cases[\$SLURM_ARRAY_TASK_ID]:-}"
[[ -n "\$CASE" ]] || { echo "Error: no instance for array task \$SLURM_ARRAY_TASK_ID" >&2; exit 1; }
STEM="\${CASE%.evrp}"
HOST="\$(hostname)"
CPU="\$(lscpu | sed -n 's/^Model name:[[:space:]]*//p' | head -1)"
echo "Instance=\$CASE Node=\$HOST CPU=\$CPU Start=\$(date -Is)"

mapfile -t arms < <(tail -n +2 arms.tsv | grep -v '^[[:space:]]*\$')
TIMING="timing/\$STEM.tsv"
printf 'arm\tinstance\tseed\tprocess_seconds\thost\tcpu\n' > "\$TIMING"
for SEED in \$(seq 1 $runs_per_instance); do
    for ROW in "\${arms[@]}"; do
        IFS=\$'\t' read -r ARM ALG ARGS <<< "\$ROW"
        T0=\$(date +%s.%N)
        # shellcheck disable=SC2086
        ./Run -alg "\$ALG" -ins "\$CASE" -root_path "\$ARM" -stp 0 -mth 0 -log 1 -seed "\$SEED" \$ARGS > /dev/null
        T1=\$(date +%s.%N)
        [[ -f "\$ARM/stats/MA/\$STEM/\$SEED/profile.tsv" ]] || { echo "Error: missing profile for \$ARM seed \$SEED" >&2; exit 1; }
        printf '%s\t%s\t%s\t%s\t%s\t%s\n' "\$ARM" "\$STEM" "\$SEED" "\$(awk -v a="\$T0" -v b="\$T1" 'BEGIN { printf "%.6f", b - a }')" "\$HOST" "\$CPU" >> "\$TIMING"
    done
done
echo "End=\$(date -Is)"
EOL
chmod +x "$project_dir/job.slurm"
echo "Prepared $project_dir: $count instances x $runs_per_instance seeds x $(($(grep -c . "$runtime_dir/arms.tsv") - 1)) arms"
echo "Submit with: sbatch $project_dir/job.slurm"
