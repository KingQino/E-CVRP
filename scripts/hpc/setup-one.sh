#!/usr/bin/env bash
# Prepares one experiment directory and its Slurm array script.
# Usage: setup-one.sh <experiment-id>
set -euo pipefail
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/common.sh"

if (( $# != 1 )); then
    echo "Usage: $0 <experiment-id>   (ids: $(experiment_ids | paste -sd ' ' -))" >&2
    exit 2
fi
id="$1"
row="$(experiment_row "$id")" || { echo "Error: unknown experiment id: $id" >&2; exit 1; }
IFS=$'\t' read -r algorithm arguments <<< "$row"
algorithm="${algorithm,,}"
folder="$(algorithm_folder "$algorithm")"

run_binary="$source_dir/build/Run"
[[ -x "$run_binary" ]] || { echo "Error: missing $run_binary; run build-source.sh first" >&2; exit 1; }

mapfile -t cases < <(instance_names)
array_max=$((${#cases[@]} - 1))
project_dir="$root_dir/$id"
build_dir="$project_dir/build"
log_dir="$build_dir/log"
mkdir -p "$log_dir"
cp "$run_binary" "$build_dir/Run"
printf '%s\n' "${cases[@]}" > "$build_dir/instances.txt"
[[ -e "$project_dir/data" ]] || ln -s "$source_dir/data" "$project_dir/data"

{
    printf 'id\talgorithm\targuments\tcommon_arguments\tinstances\truns_per_instance\n'
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$id" "$algorithm" "$arguments" "$common_args" "${#cases[@]}" "$runs_per_instance"
} > "$project_dir/configuration.tsv"
{
    git -C "$source_dir" rev-parse --abbrev-ref HEAD 2>/dev/null || true
    git -C "$source_dir" rev-parse HEAD 2>/dev/null || true
    git -C "$source_dir" status --short 2>/dev/null || true
} > "$project_dir/source-commit.txt"

cat > "$build_dir/script.slurm" <<EOL
#!/bin/bash
#SBATCH --partition=$slurm_partition
#SBATCH --job-name=ecvrp-$id
#SBATCH --output=$log_dir/%x-%A_%a.out
#SBATCH --time=$slurm_time_limit
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=$slurm_cpus
#SBATCH --mem-per-cpu=$slurm_mem_per_cpu
#SBATCH --array=0-$array_max
#SBATCH --chdir=$build_dir

# Generated by scripts/hpc/setup-one.sh. One array task = one instance, $runs_per_instance runs (seeds 1-$runs_per_instance) in parallel.
set -euo pipefail

if type module >/dev/null 2>&1; then
    module purge
    module load $run_modules
fi
export OMP_NUM_THREADS=$runs_per_instance

mapfile -t cases < <(grep -vE '^[[:space:]]*(#|\$)' instances.txt)
CASE="\${cases[\$SLURM_ARRAY_TASK_ID]:-}"
if [[ -z "\$CASE" ]]; then
    echo "Error: no instance for array task \$SLURM_ARRAY_TASK_ID" >&2
    exit 1
fi

echo "Experiment=$id Algorithm=$algorithm Instance=\$CASE Host=\$(hostname) Start=\$(date -Is)"
./Run -alg $algorithm -ins "\$CASE" $common_args $arguments

STEM="\${CASE%.evrp}"
STATS_DIR="$project_dir/stats/$folder/\$STEM"
for SEED in \$(seq 1 $runs_per_instance); do
    if [[ ! -f "\$STATS_DIR/\$SEED/solution.\$STEM.txt" ]]; then
        echo "Error: missing \$STATS_DIR/\$SEED/solution.\$STEM.txt" >&2
        exit 1
    fi
done
cat "\$STATS_DIR/stats.\$STEM.evrp"
echo "End=\$(date -Is)"
EOL
chmod +x "$build_dir/script.slurm"
echo "Prepared $id ($algorithm): ${#cases[@]} instances x $runs_per_instance runs -> $build_dir/script.slurm"
